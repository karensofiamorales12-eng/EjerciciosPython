# Ejercicio: Pedir un número y mostrar su número siguiente
numeroIngresado = float(input("Ingrese un número: "))

# Cálculo del número siguiente (sumando 1 unidad)
siguiente = numeroIngresado + 1

# Mostrar el resultado en pantalla
print("----------------------------------------")
print("El número siguiente a ", numeroIngresado, " es: ", siguiente)
print("----------------------------------------")