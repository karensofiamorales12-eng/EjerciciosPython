# Lectura de los dos números
num1 = float(input("Ingresa el primer número: "))
num2 = float(input("Ingresa el segundo número: "))

# Comparación de los números
if num1 == num2:
    print("Son iguales :b")
elif num1 < num2:
    print("El segundo número es mayor :)")
else:
    print("El primer número es mayor :)")