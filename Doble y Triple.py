# Ejercicio: Calcular y mostrar el doble y el triple de un número ingresado
numeroIngresado = float(input("Ingrese un número: "))

# Cálculos
doble = numeroIngresado * 2
triple = numeroIngresado * 3

# Mostrar los resultados en pantalla
print("----------------------------------------")
print("El doble de ", numeroIngresado, " es: ", doble)
print("El triple de ", numeroIngresado, " es: ", triple)
print("----------------------------------------")