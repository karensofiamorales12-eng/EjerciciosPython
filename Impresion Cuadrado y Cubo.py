# Ejercicio: Calcular e imprimir el cuadrado y el cubo de un número ingresado
numeroIngresado = float(input("Ingrese un número: "))

# Cálculos utilizando el operador de potencia (**)
cuadrado = numeroIngresado ** 2
cubo = numeroIngresado ** 3

# Mostrar los resultados en pantalla
print("----------------------------------------")
print("El cuadrado de ", numeroIngresado, " es: ", cuadrado)
print("El cubo de ", numeroIngresado, " es: ", cubo)
print("----------------------------------------")